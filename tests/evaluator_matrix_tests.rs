/// LIKE (R13 slice 4). WHERE and the value evaluator each have their own
/// matcher - WHERE a regex built from the pattern, the value evaluator a
/// character walk - so these rows aim at what separates the two: pattern
/// characters that mean something to a regex, and text across a newline.
///
/// | row | s               |
/// |-----|-----------------|
/// | 0   | 'abc'           |
/// | 1   | 'a.c'           |
/// | 2   | 'a(bc'          |
/// | 3   | 'line1\nline2'  |
/// | 4   | NULL            |
/// | 5   | 'ABC'           |
/// | 6   | '[a]bc'         |
fn like_table() -> DataTable {
    let mut t = DataTable::new("t");
    t.add_column(DataColumn::new("s"));
    for s in [
        Some("abc"),
        Some("a.c"),
        Some("a(bc"),
        Some("line1\nline2"),
        None,
        Some("ABC"),
        Some("[a]bc"),
    ] {
        let v = s.map_or(DataValue::Null, |s| DataValue::String(s.to_string()));
        t.add_row(DataRow::new(vec![v])).unwrap();
    }
    t
}

