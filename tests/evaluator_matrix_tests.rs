/// | 1   | 9007199254740992 | '5'   | NULL |
/// | 2   | NULL             | NULL  | 7.5  |
fn operand_table() -> DataTable {
    let mut t = DataTable::new("t");
    t.add_column(DataColumn::new("big"));
    t.add_column(DataColumn::new("s"));
    t.add_column(DataColumn::new("n"));
    let int = |v: Option<i64>| v.map_or(DataValue::Null, DataValue::Integer);
    let text = |v: Option<&str>| v.map_or(DataValue::Null, |s| DataValue::String(s.to_string()));
    let float = |v: Option<f64>| v.map_or(DataValue::Null, DataValue::Float);
    for (big, s, n) in [
        (Some(9_007_199_254_740_993), Some("5.0"), Some(5.0)),
        (Some(9_007_199_254_740_992), Some("5"), None),
        (None, None, Some(7.5)),
    ] {
        t.add_row(DataRow::new(vec![int(big), text(s), float(n)]))
            .unwrap();
    }
    t
}

