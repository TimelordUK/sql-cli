/// Rows chosen so every binary shape sees a non-NULL pair both ways round, NULL
/// on the left, NULL on the right, and NULL on both.
///
/// | row | a    | b    | s     |
/// |-----|------|------|-------|
/// | 0   | 1    | 2    | 'abc' |
/// | 1   | 2    | 1    | 'xyz' |
/// | 2   | NULL | 1    | NULL  |
/// | 3   | 1    | NULL | 'abc' |
/// | 4   | NULL | NULL | NULL  |
fn table() -> DataTable {
    let mut t = DataTable::new("t");
    t.add_column(DataColumn::new("a"));
    t.add_column(DataColumn::new("b"));
    t.add_column(DataColumn::new("s"));
    let int = |v: Option<i64>| v.map_or(DataValue::Null, DataValue::Integer);
    let text = |v: Option<&str>| v.map_or(DataValue::Null, |s| DataValue::String(s.to_string()));
    for (a, b, s) in [
        (Some(1), Some(2), Some("abc")),
        (Some(2), Some(1), Some("xyz")),
        (None, Some(1), None),
        (Some(1), None, Some("abc")),
        (None, None, None),
    ] {
        t.add_row(DataRow::new(vec![int(a), int(b), text(s)]))
            .unwrap();
    }
    t
}

