//! R13 slice 1 — the evaluator matrix.
//!
//! The engine has two evaluators for the same expression tree, and they do not
//! share rules (docs/ENGINE_REFACTORING.md § R13):
//!
//! - `RecursiveWhereEvaluator` — predicate → `Trilean`, serves `WHERE`.
//! - `ArithmeticEvaluator` — expression → `DataValue`, serves `SELECT`,
//!   `HAVING`, join conditions and, since P46, WHERE operands.
//!
//! This runs every predicate below through **both**, on every row of a table
//! built so that each operand is NULL somewhere, and compares each answer with
//! the three-valued SQL result. The expected strings were produced by DuckDB
//! (the parity reference), not derived by hand — see `EXPECTED`.
//!
//! The contract is the same as the parity corpus: a divergence is *recorded*,
//! with what we actually return, in `KNOWN`. The test fails if an unrecorded
//! divergence appears **or** if a recorded one changes — including being fixed,
//! so R13 slice 2 has to update this file to prove what it moved.
//!
//! Reading a row string: one character per table row, in row order.
//! `T`/`F`/`U` are TRUE/FALSE/UNKNOWN (NULL); `E` means the evaluator errored,
//! and `V` means the value evaluator returned a non-boolean, non-NULL value.

